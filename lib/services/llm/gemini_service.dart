import 'dart:async';
import 'package:google_generative_ai/google_generative_ai.dart';
import 'package:shared_preferences/shared_preferences.dart';
import '../../core/constants/app_constants.dart';
import '../../core/errors/app_error.dart';

/// Service for interfacing with the Google Gemini API.
///
/// Targets the Gemini 3.x series (updated September 2026).
/// Primary model: gemini-3.8-flash
/// Fallback model: gemini-3.5-flash-lite
///
/// Features:
/// - Real-time token streaming via [tokenStream]
/// - Automatic model fallback on 429 / 503 / high demand
/// - Persistent API key + model selection via SharedPreferences
/// - Auto-migration from deprecated model IDs on launch
class GeminiService {
  String _apiKey = '';
  String _modelName = AppConstants.defaultGeminiModel;
  bool _generating = false;
  bool _stopRequested = false;

  final StreamController<String> _tokenStreamController =
      StreamController<String>.broadcast();

  /// Stream of token pieces generated by Gemini in real-time.
  Stream<String> get tokenStream => _tokenStreamController.stream;

  String get apiKey => _apiKey;
  String get modelName => _modelName;
  bool get isConfigured => _apiKey.trim().isNotEmpty;
  bool get isGenerating => _generating;

  // ─── Deprecated model IDs that need auto-migration ───────────────────────
  static const _deprecatedModels = {
    'gemini-1.5-flash',
    'gemini-1.5-pro',
    'gemini-2.0-flash',
    'gemini-2.0-flash-lite',
    'gemini-2.5-flash',
    'gemini-2.5-pro',
    'gemini-3.7-flash',
  };

  /// Loads saved API key and model from [SharedPreferences].
  /// Automatically migrates deprecated/unavailable model names to the current default.
  Future<void> initialize() async {
    final prefs = await SharedPreferences.getInstance();

    final savedKey = prefs.getString(AppConstants.prefGeminiApiKey);
    _apiKey = (savedKey != null && savedKey.isNotEmpty)
        ? savedKey
        : AppConstants.defaultGeminiApiKey;

    final savedModel = prefs.getString(AppConstants.prefGeminiModel);
    String targetModel = (savedModel != null && savedModel.isNotEmpty)
        ? savedModel
        : AppConstants.defaultGeminiModel;

    // Auto-migrate if saved model is deprecated or no longer in the available list
    if (_deprecatedModels.contains(targetModel) ||
        !AppConstants.availableGeminiModels.contains(targetModel)) {
      targetModel = AppConstants.defaultGeminiModel;
      await prefs.setString(AppConstants.prefGeminiModel, targetModel);
    }

    _modelName = targetModel;
  }

  /// Updates and persists the Gemini API key.
  Future<void> setApiKey(String key) async {
    _apiKey = key.trim();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(AppConstants.prefGeminiApiKey, _apiKey);
  }

  /// Updates and persists the selected Gemini model.
  Future<void> setModel(String model) async {
    _modelName = model.trim();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(AppConstants.prefGeminiModel, _modelName);
  }

  /// Signals immediate stop of ongoing streaming generation.
  void stopGeneration() {
    _stopRequested = true;
    _generating = false;
  }

  /// Tests API key connectivity with a lightweight probe.
  /// Uses the full fallback chain on high-demand / unavailability errors.
  Future<String> testConnection({String? testApiKey, String? testModel}) async {
    final keyToUse = (testApiKey ?? _apiKey).trim();

    if (keyToUse.isEmpty) {
      throw const InferenceError(
        'Gemini API key is not configured. Please enter your API key in Settings.',
      );
    }

    // Sanitize requested model — fall back to default if deprecated/unknown
    String primaryModel = (testModel ?? _modelName).trim();
    if (_deprecatedModels.contains(primaryModel) ||
        !AppConstants.availableGeminiModels.contains(primaryModel)) {
      primaryModel = AppConstants.defaultGeminiModel;
    }

    // Build candidate chain starting from requested model
    final candidateModels = _buildCandidateChain(primaryModel);

    Object? lastError;
    for (int i = 0; i < candidateModels.length; i++) {
      final candidate = candidateModels[i];
      try {
        final model = GenerativeModel(
          model: candidate,
          apiKey: keyToUse,
          generationConfig: GenerationConfig(
            temperature: 0.1,
            maxOutputTokens: 64,
          ),
        );

        final response = await model.generateContent([
          Content.text('Say "Gemini API connected successfully!" in one short sentence.'),
        ]);

        final text = response.text?.trim();
        if (text != null && text.isNotEmpty) {
          if (candidate != primaryModel) {
            return '$text\n(Note: Connected via $candidate — $primaryModel is currently busy or unavailable.)';
          }
          return text;
        }
      } catch (e) {
        lastError = e;
        if (i < candidateModels.length - 1) {
          await Future.delayed(const Duration(milliseconds: 700));
        }
      }
    }

    throw InferenceError(_formatFriendlyError(lastError.toString()));
  }

  /// Generate a streaming response with automatic high-demand resilience.
  ///
  /// Uses [AppConstants.fallbackModelChain] so that if the primary model is
  /// unavailable (503/429/high demand), the service silently switches to the
  /// next available model in the chain.
  Future<String> generate({
    required String prompt,
    String? systemInstruction,
    int maxTokens = AppConstants.defaultMaxOutputTokens,
    double temperature = 0.7,
  }) async {
    if (!isConfigured) {
      throw const InferenceError(
        'Gemini API key is not configured. Please configure your API key in Settings.',
      );
    }
    if (_generating) {
      throw const InferenceError('Already generating a response.');
    }

    _generating = true;
    _stopRequested = false;

    // Sanitize primary model choice
    String primaryModel = _modelName;
    if (_deprecatedModels.contains(primaryModel) ||
        !AppConstants.availableGeminiModels.contains(primaryModel)) {
      primaryModel = AppConstants.defaultGeminiModel;
    }

    final candidateModels = _buildCandidateChain(primaryModel);
    Object? lastError;

    for (int i = 0; i < candidateModels.length; i++) {
      final currentModel = candidateModels[i];
      final buffer = StringBuffer();

      try {
        final model = GenerativeModel(
          model: currentModel,
          apiKey: _apiKey,
          systemInstruction: (systemInstruction != null && systemInstruction.isNotEmpty)
              ? Content.system(systemInstruction)
              : null,
          generationConfig: GenerationConfig(
            temperature: temperature,
            maxOutputTokens: maxTokens,
          ),
        );

        final streamResponse = model.generateContentStream([Content.text(prompt)]);

        await for (final chunk in streamResponse) {
          if (_stopRequested) break;
          final piece = chunk.text ?? '';
          if (piece.isNotEmpty) {
            buffer.write(piece);
            _tokenStreamController.add(piece);
          }
        }

        if (buffer.isNotEmpty) {
          _generating = false;
          _stopRequested = false;
          return buffer.toString();
        }
      } catch (e) {
        lastError = e;
        final errorStr = e.toString().toLowerCase();

        // Determine if this error is recoverable (demand spike / model unavailable)
        final isRecoverable = errorStr.contains('demand') ||
            errorStr.contains('overload') ||
            errorStr.contains('503') ||
            errorStr.contains('429') ||
            errorStr.contains('resource_exhausted') ||
            errorStr.contains('unavailable') ||
            errorStr.contains('not found') ||
            errorStr.contains('no longer available') ||
            errorStr.contains('is not supported') ||
            errorStr.contains('deprecated');

        if (isRecoverable && i < candidateModels.length - 1) {
          // Notify user of the switch in the streaming bubble
          if (buffer.isNotEmpty) {
            _tokenStreamController.add(
              '\n\n*(Switching to ${candidateModels[i + 1]} due to temporary high demand on $currentModel…)*\n\n',
            );
          }
          await Future.delayed(const Duration(milliseconds: 1200));
          continue;
        }

        break;
      }
    }

    _generating = false;
    _stopRequested = false;
    throw InferenceError(_formatFriendlyError(lastError.toString()));
  }

  // ─── Helpers ─────────────────────────────────────────────────────────────

  /// Builds an ordered candidate list starting with [primaryModel],
  /// then all remaining models from [AppConstants.fallbackModelChain].
  List<String> _buildCandidateChain(String primaryModel) {
    final chain = <String>[primaryModel];
    for (final m in AppConstants.fallbackModelChain) {
      if (m != primaryModel) chain.add(m);
    }
    return chain;
  }

  static String _formatFriendlyError(String rawError) {
    final lower = rawError.toLowerCase();
    if (lower.contains('demand') || lower.contains('overload') || lower.contains('503')) {
      return 'Gemini servers are experiencing peak demand. All fallback models were also busy. Please try again in a few seconds.';
    }
    if (lower.contains('api_key') ||
        lower.contains('invalid') ||
        lower.contains('unauthenticated') ||
        lower.contains('403')) {
      return 'Invalid Gemini API key or unauthorized access. Please verify your API key in Settings.';
    }
    if (lower.contains('quota') ||
        lower.contains('429') ||
        lower.contains('resource_exhausted')) {
      return 'Gemini API quota/rate limit reached. Please wait a moment before sending another query.';
    }
    if (lower.contains('deprecated') ||
        lower.contains('not found') ||
        lower.contains('no longer available')) {
      return 'The selected Gemini model is no longer available. The app has automatically switched to the latest available model. Please retry.';
    }
    return 'Gemini API Error: $rawError';
  }

  void dispose() {
    _tokenStreamController.close();
  }
}
